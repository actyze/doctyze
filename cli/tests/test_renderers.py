"""Tests for individual renderers."""
from __future__ import annotations

from pathlib import Path

import yaml

from doctyze import renderers


def test_registry_has_all_five_renderers() -> None:
    assert set(renderers.REGISTRY) == {
        "claude", "cursor", "copilot", "windsurf", "holmes",
    }


def test_registry_get_is_case_insensitive() -> None:
    assert isinstance(renderers.get("CLAUDE"), renderers.Renderer)
    assert isinstance(renderers.get("Claude"), renderers.Renderer)


def test_registry_get_unknown_raises_keyerror() -> None:
    try:
        renderers.get("definitely-not-a-vendor")
    except KeyError as exc:
        assert "definitely-not-a-vendor" in str(exc)
    else:
        raise AssertionError("expected KeyError")


# ── Claude renderer ────────────────────────────────────────────────────

def test_claude_renderer_creates_subdir_per_skill(fixture_repo: Path) -> None:
    r = renderers.get("claude")
    written = r.render(fixture_repo)
    assert len(written) == 1
    target = fixture_repo / ".claude" / "skills" / "write-adr" / "SKILL.md"
    assert target.exists()
    assert target in written


def test_claude_skill_md_preserves_name_and_description(fixture_repo: Path) -> None:
    renderers.get("claude").render(fixture_repo)
    content = (fixture_repo / ".claude" / "skills" / "write-adr" / "SKILL.md").read_text()
    # Frontmatter intact
    assert "name: write-adr" in content
    assert "description: Use when adding" in content
    # Body intact (banner is between frontmatter and body)
    assert "# How to write an ADR" in content
    # Generated banner so contributors know not to hand-edit
    assert "Generated by Doctyze" in content


def test_claude_renderer_dry_run_does_not_write(fixture_repo: Path) -> None:
    r = renderers.get("claude")
    written = r.render(fixture_repo, dry_run=True)
    assert len(written) == 1
    # The target was *named* but not created
    assert not (fixture_repo / ".claude" / "skills" / "write-adr" / "SKILL.md").exists()


