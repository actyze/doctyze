# ── Holmes renderer ────────────────────────────────────────────────────

def test_holmes_renderer_writes_yaml_per_runbook(fixture_repo: Path) -> None:
    written = renderers.get("holmes").render(fixture_repo)
    assert len(written) == 1
    target = fixture_repo / ".holmes" / "runbooks" / "high-error-rate.yaml"
    assert target.exists()
    assert written == [target]


def test_holmes_renderer_produces_valid_yaml_with_expected_shape(fixture_repo: Path) -> None:
    renderers.get("holmes").render(fixture_repo)
    target = fixture_repo / ".holmes" / "runbooks" / "high-error-rate.yaml"
    parsed = yaml.safe_load(target.read_text())
    assert parsed["apiVersion"] == "holmesgpt/v1"
    assert parsed["kind"] == "Runbook"
    assert parsed["metadata"]["service"] == "orders-api"
    assert parsed["metadata"]["runbook_id"] == "high-error-rate"
    assert parsed["spec"]["match"]["alert_names"] == ["OrdersApiHighErrorRate"]
    assert parsed["spec"]["match"]["labels"]["severity"] == "high"
    assert parsed["spec"]["read_only"] is True
    # Body content lifted into instructions
    assert "5xx rate" in parsed["spec"]["instructions"]


def test_holmes_falls_back_to_filename_stem_when_no_runbook_id(tmp_path: Path) -> None:
    """If frontmatter is missing runbook_id, use the file stem."""
    rb_dir = tmp_path / "docs" / "runbooks"
    rb_dir.mkdir(parents=True)
    (rb_dir / "no-id.md").write_text(
        "---\nservice: foo\nseverity: medium\n---\nBody.\n"
    )
    written = renderers.get("holmes").render(tmp_path)
    assert written[0].name == "no-id.yaml"
